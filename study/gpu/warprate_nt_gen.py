#!/usr/bin/env python3
"""Generates warprate_nt.cu: one warp's cost of not-taken / taken conditional branches.
Body: 128 integer ops on 8 independent chains (add/xor alternating, the warprate int_ind8 pattern).
  base        no branch
  ntN         a never-taken @P bra every N ops (N = 1, 2, 4, 16); the target is an out-of-line
              loop that jumps back to the fall-through point (so the fall-through has two
              predecessors and the branches cannot be threaded or if-converted)
  ftN         an always-taken forward @P bra over a never-executed inline loop (warprate br_everyN form)
  btN         a backward-taken branch: inner loop of N ops whose back-edge is taken (trip count 128/N per
              outer iteration; the loop counter adds 1 IADD + 1 ISETP per inner iteration)
  pat_*       every 4 ops: a Galois LFSR step (6 ops) computes predicate Q from the low bit, then
              @Q bra to an out-of-line block that executes once and returns. Same code for every
              pattern; pattern chosen at run time: never / always / alternate / lfsr (pseudo-random)
"""
import sys
OPS = []
for c in range(8): OPS.append(f"add.u32 %{c}, %{c}, %8;")
for c in range(8): OPS.append(f"xor.b32 %{c}, %{c}, %9;")
def ops(n, start): return [OPS[(start + i) % 16] for i in range(n)]
out = []
def kernel(name, body_lines, tails=(), decl="", extra_in=""):
    s = "\\n\\t".join(body_lines)
    t = "\\n\\t".join(tails)
    asmtxt = '"{\\n\\t.reg .pred P, Q, R;\\n\\t' + decl + 'setp.ne.u32 P, %10, 0;\\n\\t' + s + '\\n\\tbra.uni END_%=;\\n\\t' + t + '\\n\\tEND_%=:\\n\\t}"'
    out.append((name, asmtxt))
# base
out_base = ops(128, 0)
kernel("base", out_base)
for N in (1, 2, 4, 16):
    b, tails = [], []
    for g in range(128 // N):
        b += ops(N, g * N)
        b += [f"@!P bra.uni S{g}_%=;", f"C{g}_%=:"]   # P is true at run time -> !P false -> never taken
        tails += [f"S{g}_%=:", "add.u32 %4, %4, %9;", "setp.ne.u32 R, %4, 0;", f"@R bra.uni S{g}_%=;", f"bra.uni C{g}_%=;"]
    kernel(f"nt{N}", b, tails)
for N in (1, 4, 16):
    b = []
    for g in range(128 // N):
        b += ops(N, g * N)
        b += [f"@P bra.uni L{g}_%=;", f"S{g}_%=:", "add.u32 %4, %4, %9;", "setp.ne.u32 R, %4, 0;", f"@R bra.uni S{g}_%=;", f"L{g}_%=:"]
    kernel(f"ft{N}", b)
for N in (4, 16):
    # inner loop: N ops + counter, back-edge taken (128/N - 1) of 128/N times
    b = ["mov.u32 %11, 0;", f"IN_%=:"] + ops(N, 0) + ["add.u32 %11, %11, 1;", f"setp.lt.u32 Q, %11, {128 // N};", "@Q bra.uni IN_%=;"]
    kernel(f"bt{N}", b)
    b = ["mov.u32 %11, 0;", f"IN_%=:"] + ops(N, 0) + ["add.u32 %11, %11, 1;", f"setp.lt.u32 Q, %11, {128 // N};", "@Q bra.uni IN_%=;"]
# runtime-trip-count loops: per group "mov cnt,0; L: N ops; cnt++; setp.lt Q, cnt, T; @Q bra L"
# T = %12 (run time). The back-edge is taken T-1 times and not taken once per entry, so
# cycles per group = T * (N ops + IADD + ISETP + taken BRA) + (not-taken - taken) + MOV.
for N in (4, 16):
    b = []
    for g in range(128 // N):
        b += ["mov.u32 %14, 0;", f"LT{g}_%=:"] + ops(N, g * N) + ["add.u32 %14, %14, 1;", "setp.lt.u32 Q, %14, %12;", f"@Q bra.uni LT{g}_%=;"]
    kernel(f"lt{N}", b)
# pattern kernel: %12 = r (LFSR state), %13 = taps, %14 scratch, %15 scratch
b, tails = [], []
for g in range(32):
    b += ops(4, g * 4)
    b += ["and.b32 %14, %12, 1;", "setp.ne.u32 Q, %14, 0;", "sub.u32 %15, 0, %14;", "and.b32 %15, %15, %13;", "shr.u32 %12, %12, 1;", "xor.b32 %12, %12, %15;",
          f"@Q bra.uni S{g}_%=;", f"C{g}_%=:"]
    tails += [f"S{g}_%=:", "add.u32 %5, %5, %9;", "setp.eq.u32 R, %5, %10;", f"@R bra.uni S{g}_%=;", f"bra.uni C{g}_%=;"]
kernel("pat", b, tails)
# pattern kernel without branch (same LFSR work) as its base
b = []
for g in range(32):
    b += ops(4, g * 4)
    b += ["and.b32 %14, %12, 1;", "setp.ne.u32 Q, %14, 0;", "sub.u32 %15, 0, %14;", "and.b32 %15, %15, %13;", "shr.u32 %12, %12, 1;", "xor.b32 %12, %12, %15;",
          "selp.u32 %14, 1, 0, Q;", "add.u32 %6, %6, %14;"]   # consume Q without a branch (2 ops in place of bra + label)
kernel("pat_nobr", b)

src = ['// Generated by warprate_nt_gen.py. One warp, clock64 timing, %globaltimer check.',
       '#include <cuda_runtime.h>', '#include <cstdio>', '#include <cstdlib>', '#include <cstring>', '#include <vector>', '#include <algorithm>', '#include "tpc_smctrl.h"',
       'struct Rec { long long c0, c1; unsigned long long g0, g1; int smid; };']
for i, (name, a) in enumerate(out):
    src.append(f'__global__ void k_{name}(int iters, unsigned y, unsigned r0, unsigned taps, Rec* rec, unsigned* sink) {{')
    src.append('  uint32_t a0 = threadIdx.x, a1 = a0 + 1, a2 = a0 + 2, a3 = a0 + 3, a4 = a0 + 4, a5 = a0 + 5, a6 = a0 + 6, a7 = a0 + 7;')
    src.append('  const uint32_t z = y * 0x9e3779b1u; uint32_t cnt = 0, r = r0, s1 = 0, s2 = 0; const uint32_t py = y;')
    src.append('  long long c0; unsigned long long g0; asm volatile("mov.u64 %0, %%globaltimer;" : "=l"(g0)); c0 = clock64();')
    src.append('#pragma unroll 1')
    src.append('  for (int it = 0; it < iters; ++it) {')
    src.append(f'    asm volatile({a} : "+r"(a0), "+r"(a1), "+r"(a2), "+r"(a3), "+r"(a4), "+r"(a5), "+r"(a6), "+r"(a7) : "r"(y), "r"(z), "r"(py), "r"(cnt), "r"(r), "r"(taps), "r"(s1), "r"(s2));')
    src.append('  }')
    src.append('  long long c1 = clock64(); unsigned long long g1; asm volatile("mov.u64 %0, %%globaltimer;" : "=l"(g1));')
    src.append('  if (threadIdx.x == 0) { unsigned s; asm volatile("mov.u32 %0, %%smid;" : "=r"(s)); rec->c0 = c0; rec->c1 = c1; rec->g0 = g0; rec->g1 = g1; rec->smid = s; }')
    src.append('  if ((a0 ^ a1 ^ a2 ^ a3 ^ a4 ^ a5 ^ a6 ^ a7) == 0x12345u) *sink = a0;')
    src.append('}')
names = [n for n, _ in out]
src.append('typedef void (*KF)(int, unsigned, unsigned, unsigned, Rec*, unsigned*);')
src.append('static KF kf[] = {' + ", ".join(f"k_{n}" for n in names) + '};')
src.append('static const char* kn[] = {' + ", ".join(f'"{n}"' for n in names) + '};')
src.append(r'''int main(int argc, char** argv) {
  int iters = 20000, reps = 5;
  Rec* rec; unsigned* sink; cudaMalloc(&rec, sizeof(Rec)); cudaMalloc(&sink, 4);
  struct Pat { const char* n; unsigned r0, taps; } pats[] = {{"never", 0u, 0xB4BCD35Cu}, {"always", 0xFFFFFFFFu, 0x80000000u},
                                                            {"alternate", 0x55555555u, 0x80000000u}, {"lfsr", 0xACE1u, 0xB4BCD35Cu}};
  const int nk = sizeof(kf) / sizeof(kf[0]);
  for (int k = 0; k < nk; ++k) {
    const bool pat = !strncmp(kn[k], "pat", 3), lt = !strncmp(kn[k], "lt", 2);
    const unsigned trips[4] = {1, 2, 4, 8};
    for (int p = 0; p < (pat || lt ? 4 : 1); ++p) {
      std::vector<double> cyc; double ghz = 0; int sm = -1;
      for (int r = 0; r <= reps; ++r) {
        tpc_next_enable(u128_bit(0));
        kf[k]<<<1, 32>>>(iters, 3u, lt ? trips[p] : pats[p].r0, pats[p].taps, rec, sink);
        if (cudaDeviceSynchronize() != cudaSuccess) { printf("error %s\n", kn[k]); return 1; }
        Rec h; cudaMemcpy(&h, rec, sizeof h, cudaMemcpyDeviceToHost);
        if (r == 0) continue;
        cyc.push_back((double)(h.c1 - h.c0) / iters); ghz = (double)(h.c1 - h.c0) / (double)(h.g1 - h.g0); sm = h.smid;
      }
      std::sort(cyc.begin(), cyc.end());
      char pn[32]; if (lt) snprintf(pn, sizeof pn, "trip%u", trips[p]); else snprintf(pn, sizeof pn, "%s", pat ? pats[p].n : "-");
      printf("kernel=%s pattern=%s iters=%d reps=%d smid=%d cyc_per_iter_med=%.2f min=%.2f max=%.2f ghz_from_globaltimer=%.3f\n",
             kn[k], pn, iters, reps, sm, cyc[cyc.size() / 2], cyc.front(), cyc.back(), ghz);
    }
  }
  return 0;
}''')
open(sys.argv[1], "w").write("\n".join(src) + "\n")
